def _parse_row_line(line):
    """Parse a table row or bullet without a backtracking-heavy regex."""
    if line.startswith("|"):
        if not line.endswith("|"):
            return None
        body = line[1:-1]
        start = body.find("[")
        sep = body.find("](", start + 1) if start >= 0 else -1
        if start < 0 or sep < 0:
            return None
        end = body.find(")", sep + 2)
        if end < 0:
            return None
        name = body[start + 1:sep].strip()
        url = body[sep + 2:end].strip()
        rest = body[end + 1:].strip()
        if rest.startswith("|"):
            rest = rest[1:].strip()
        return name, url, rest
    if line.startswith("- **["):
        start = line.find("[")
        sep = line.find("](", start + 1)
        if start < 0 or sep < 0:
            return None
        end = line.find(")", sep + 2)
        if end < 0:
            return None
        close = line.find("**", end + 1)
        name = line[start + 1:sep].strip()
        url = line[sep + 2:end].strip()
        rest = line[close + 2:] if close >= 0 else line[end + 1:]
        rest = rest.lstrip(" -–—").strip()
        return name, url, rest
    return None


def _parse_table(text, source_path, category_ids, platform="Apify", sponsored=False,
                 collection="", errors=None):
    rows = []
    current_heading = ""
    for line_no, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        heading = HEADING_RE.match(line)
        if heading:
            current_heading = _strip_markdown(heading.group("title"))
            continue
        if not line.startswith(("| [", "- **[")):
            continue
        parsed = _parse_row_line(line)
        if parsed is None:
            match = TABLE_ROW_RE.match(line) or BULLET_RE.match(line)
            parsed = (
                match.group("name"), match.group("url"), match.group("desc")
            ) if match else None
        if parsed is None:
            if errors is not None:
                errors.append({
                    "source_path": source_path,
                    "line": line_no,
                    "code": "row_unparsed",
                    "message": line[:220],
                })
            continue
        name, url, desc = parsed
        if not url:
            if errors is not None:
                errors.append({
                    "source_path": source_path,
                    "line": line_no,
                    "code": "url_missing",
                    "message": name[:160],
                })
            continue
        row_categories = list(category_ids)
        if collection and current_heading and current_heading.lower() != "api categories":
            row_categories = ["%s::%s" % (collection, _slug(current_heading))]
        rows.append({
            "name": name,
            "description": desc,
            "source_url": url,
            "source_path": source_path,
            "category_ids": row_categories,
            "platform": platform,
            "sponsored": sponsored,
            "collection": collection,
            "listing_source": "featured_collection" if sponsored else "core_directory",
        })
    return rows


def _category_label(slug):
    known = {
        "ai": "AI", "mcp-servers": "MCP Servers", "seo-tools": "SEO Tools",
        "developer-tools": "Developer Tools", "lead-generation": "Lead Generation",
        "real-estate": "Real Estate", "social-media": "Social Media",
        "open-source": "Open Source", "for-creators": "For Creators",
        "ecommerce": "Ecommerce", "videos": "Videos",
    }
    if slug in known:
        return known[slug]
    return " ".join(
        word.capitalize() for word in re.split(r"[-_]+", slug) if word
    )


def _first_paragraph(text):
    lines = text.splitlines()
    started = False
    for raw in lines:
        line = raw.strip()
        if not started:
            if line.startswith("#"):
                started = True
            continue
        if not line or line.startswith(("#", "<", "**", "|", "[")):
            if line.startswith("**") and len(line) > 60:
                return _strip_markdown(line.strip("*").strip())
            continue
        if line.startswith("-") or line.startswith(">"):
            continue
        return _strip_markdown(line)
    return ""


def _enrichment(root):
    """Full descriptions from the pipeline's own actor document, keyed by URL."""
    path = os.path.join(root, "settings", "APIFY_ACTORS.md")
    if not os.path.isfile(path):
        return {}
    try:
        text = _read_text(path)
    except OSError:
        return {}
    out = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line.startswith("- **["):
            continue
        match = BULLET_RE.match(line)
        if not match:
            continue
        key = canonical_url(match.group("url"))
        desc = _strip_markdown(match.group("desc"))
        if key and len(desc) > len(out.get(key, "")):
            out[key] = desc[:MAX_DESCRIPTION]
    return out


def parse_repository(root, commit="", synced_at=""):
    """Parse a repository snapshot into an index. Never executes repository code."""
    generated_at = _now()
    errors = []
    core_categories = []
    rows = []

    try:
        names = sorted(os.listdir(root))
    except OSError as exc:
        raise CatalogError("Cannot read the repository snapshot: %s" % exc,
                           "repo_unreadable", 503)

    category_lookup = {}
    for name in names:
        match = CATEGORY_RE.match(name)
        if not match or name == "00-featured-apis":
            continue
        full = os.path.join(root, name)
        if not os.path.isdir(full):
            continue
        readme = os.path.join(full, "README.md")
        slug = match.group("slug")
        label = _category_label(slug)
        category_lookup[name] = label
        parsed = 0
        text = ""
        if os.path.isfile(readme):
            try:
                text = _read_text(readme)
                parsed_rows = _parse_table(
                    text, name + "/README.md", [name], errors=errors
                )
                rows.extend(parsed_rows)
                parsed = len(parsed_rows)
            except OSError as exc:
                errors.append({
                    "source_path": name + "/README.md",
                    "line": 0,
                    "code": "read_failed",
                    "message": str(exc),
                })
        else:
            errors.append({
                "source_path": name + "/README.md",
                "line": 0,
                "code": "readme_missing",
                "message": "Category folder has no README.md",
            })
        core_categories.append({
            "id": name,
            "slug": slug,
            "name": label,
            "declared_count": int(match.group("count")),
            "count": parsed,
            "path": name,
            "readme": name + "/README.md" if os.path.isfile(readme) else "",
            "description": _first_paragraph(text),
            "source_url": "%s/tree/main/%s" % (REPOSITORY_URL, name),
            "featured": False,
        })

    # Featured / sponsored collections are separate directories.
    featured_meta = []
    featured_rows = []
    featured_root = os.path.join(root, "00-featured-apis")
    if os.path.isdir(featured_root):
        for collection in sorted(os.listdir(featured_root)):
            collection_dir = os.path.join(featured_root, collection)
            readme = os.path.join(collection_dir, "README.md")
            if not os.path.isdir(collection_dir) or not os.path.isfile(readme):
                continue
            try:
                text = _read_text(readme)
            except OSError as exc:
                errors.append({
                    "source_path": "00-featured-apis/%s/README.md" % collection,
                    "line": 0,
                    "code": "read_failed",
                    "message": str(exc),
                })
                continue
            platform = "APIMesa" if "apimesa" in collection.lower() else "Featured"
            parsed_rows = _parse_table(
                text,
                "00-featured-apis/%s/README.md" % collection,
                [],
                platform=platform,
                sponsored=True,
                collection=collection,
                errors=errors,
            )
            # Add the featured sub-categories to the lookup used by cards.
            for row in parsed_rows:
                for cid in row["category_ids"]:
                    if cid not in category_lookup:
                        category_lookup[cid] = cid.split("::", 1)[-1].replace("-", " ").title()
            featured_rows.extend(parsed_rows)
            title_match = re.search(r"^#\s+(.+)$", text, re.MULTILINE)
            featured_meta.append({
                "id": collection,
                "name": _strip_markdown(title_match.group(1)) if title_match else collection,
                "description": _first_paragraph(text),
                "path": collection,
                "readme": "00-featured-apis/%s/README.md" % collection,
                "count": len(parsed_rows),
                "sponsored": True,
                "source_url": "%s/tree/main/00-featured-apis/%s" % (
                    REPOSITORY_URL, collection),
                "categories": sorted({
                    row["category_ids"][0].split("::", 1)[-1].replace("-", " ").title()
                    for row in parsed_rows if row.get("category_ids")
                }),
            })

    # Merge duplicate core rows by stable ID while preserving every category.
    merged = {}
    duplicates = 0
    skipped = 0
    for row in rows:
        try:
            entry = derive_entry(row, category_lookup, commit, generated_at)
        except Exception as exc:  # malformed row must not discard valid rows
            skipped += 1
            errors.append({
                "source_path": row.get("source_path", ""),
                "line": 0,
                "code": "row_derive_failed",
                "message": str(exc)[:220],
            })
            continue
        key = entry["id"]
        if key in merged:
            duplicates += 1
            existing = merged[key]
            existing["category_ids"] = sorted(set(existing["category_ids"]) | set(entry["category_ids"]))
            existing["categories"] = [
                {"id": cid, "name": category_lookup.get(cid, cid)}
                for cid in existing["category_ids"]
            ]
            if not existing.get("description") and entry.get("description"):
                existing["description"] = entry["description"]
            existing["fingerprint"] = fingerprint(existing)
            continue
        merged[key] = entry

    enrichment = _enrichment(root)
    if enrichment:
        for entry in merged.values():
            key = canonical_url(entry.get("source_url"))
            better = enrichment.get(key)
            if better and len(better) > len(entry.get("description") or ""):
                entry["description"] = better
                entry["description_source"] = "settings/APIFY_ACTORS.md"
                entry["fingerprint"] = fingerprint(entry)

    featured_entries = []
    featured_seen = set()
    for row in featured_rows:
        try:
            entry = derive_entry(row, category_lookup, commit, generated_at)
        except Exception as exc:
            skipped += 1
            errors.append({
                "source_path": row.get("source_path", ""),
                "line": 0,
                "code": "row_derive_failed",
                "message": str(exc)[:220],
            })
            continue
        if entry["id"] in featured_seen:
            skipped += 1
            continue
        featured_seen.add(entry["id"])
        featured_entries.append(entry)

    entries = sorted(merged.values(), key=lambda item: item["name"].casefold())
    entries.extend(sorted(featured_entries, key=lambda item: item["name"].casefold()))

    # Actual counts are computed from parsed records, never folder suffixes.
    counts_by_category = {}
    for entry in entries:
        for cid in entry.get("category_ids") or []:
            counts_by_category[cid] = counts_by_category.get(cid, 0) + 1
    for category in core_categories:
        category["count"] = counts_by_category.get(category["id"], 0)
        category["declared_count"] = category["declared_count"]

    actual = {
        "entries": len(entries),
        "listings": len(rows) + len(featured_rows),
        "core_entries": len(merged),
        "featured_entries": len(featured_entries),
        "categories": len(core_categories),
        "featured_collections": len(featured_meta),
        "duplicates_merged": duplicates,
        "skipped": skipped,
        "parse_errors": len(errors),
    }
    return {
        "version": 1,
        "parser_version": PARSER_VERSION,
        "generated_at": generated_at,
        "source": {
            "repository": REPOSITORY_URL,
            "branch": megalist.BRANCH,
            "commit": commit or "",
            "synced_at": synced_at or "",
        },
        "counts": actual,
        "categories": core_categories,
        "featured": featured_meta,
        "entries": entries,
        "errors": errors[:500],
        "error_count": len(errors),
    }


