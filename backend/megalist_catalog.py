def readiness_plan(entry):
    """Derive a proposed integration plan. Never claims a connection is live."""
    kind = entry.get("integration_type") or "unknown"
    auth = entry.get("authentication_type") or "unknown"
    auth_basis = entry.get("authentication_evidence") or ""
    docs = entry.get("documentation_url")
    source = entry.get("source_url")
    sponsored = bool(entry.get("sponsored"))
    provider = entry.get("provider_name") or "Unknown provider"

    if kind == "mcp_server":
        approach = "MCP server"
        limitations = [
            "The catalog row is an MCP listing/description, not an endpoint.",
            "No MCP endpoint, transport, installation manifest, or tool schema is present in the source.",
            "Installation or connection requires separate review and owner approval.",
        ]
        prerequisites = [
            "Locate the server's repository/package and audit its code.",
            "Confirm transport (stdio/SSE/HTTP) and required permissions.",
            "Run it in an isolated environment before enabling any tool.",
        ]
    elif kind == "scraping_service":
        approach = "Apify Actor via Apify API/SDK"
        limitations = [
            "The row links to an Apify Store actor page, not a direct REST endpoint.",
            "The actor's input schema and output fields are not indexed here.",
            "Running an actor consumes Apify platform usage/credits.",
        ]
        prerequisites = [
            "Review the actor page and input schema.",
            "Provide an Apify API token through the existing credential mechanism.",
            "Build an adapter that maps this workspace's tool contract to the actor.",
        ]
    elif kind == "marketplace_listing":
        approach = "Marketplace listing; adapter required"
        limitations = [
            "The source links to a marketplace listing, not an executable endpoint.",
            "No API base URL, SDK, or credential contract is stated by the source.",
            "A connection cannot be prepared until official documentation is reviewed.",
        ]
        prerequisites = [
            "Open the listing and identify the provider's official API documentation.",
            "Record the documented base URL, authentication scheme, and rate limits.",
            "Write and review a proposed adapter specification.",
        ]
    elif kind == "api":
        approach = "HTTP API (documentation required)"
        limitations = [
            "The source claims API access but does not provide an endpoint or schema.",
            "Authentication and limits must come from official documentation.",
        ]
        prerequisites = [
            "Verify the official documentation URL.",
            "Capture the base URL, auth method, and rate limits.",
            "Prepare a proposed adapter specification before any request.",
        ]
    else:
        approach = "Unclassified"
        limitations = [
            "The source does not contain enough metadata to classify the integration.",
        ]
