def read_history():
    path = history_path()
    if not os.path.isfile(path):
        return []
    try:
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return []
    records = data.get("records") if isinstance(data, dict) else data
    return [item for item in (records or []) if isinstance(item, dict)]


def record_history(status, index=None, trigger="manual", error=""):
    records = read_history()
    counts = (index or {}).get("counts") or {}
    source = (index or {}).get("source") or {}
    records.insert(0, {
        "id": "sync-%d" % int(time.time() * 1000),
        "at": _now(),
        "trigger": trigger,
        "status": status,
        "commit": source.get("commit") or "",
        "parser_version": (index or {}).get("parser_version") or PARSER_VERSION,
        "counts": counts,
        "import": (index or {}).get("import") or {},
        "error": str(error or "")[:500],
    })
    del records[50:]
    try:
        _atomic_write_json(history_path(), {"records": records})
    except OSError:
        pass
    return records


