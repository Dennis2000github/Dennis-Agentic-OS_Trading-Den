def _now():
    return time.strftime("%Y-%m-%dT%H:%M:%S%z")


def index_path():
    return os.path.join(megalist.PACK_DIR, INDEX_FILENAME)


def history_path():
    return os.path.join(megalist.PACK_DIR, "SYNC_HISTORY.json")


def _read_text(path):
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        return fh.read()


def _clean(value):
    text = str(value or "").replace("\u00a0", " ")
    return " ".join(text.split())


@lru_cache(maxsize=60000)
def _strip_markdown(value):
    text = _clean(value)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[`*_~]+", "", text)
    return _clean(text)


def _slug(value):
    text = re.sub(r"[^a-z0-9]+", "-", str(value or "").lower()).strip("-")
    return text[:80] or "entry"


@lru_cache(maxsize=60000)
def _host(url):
    try:
        return (urllib.parse.urlsplit(str(url or "")).hostname or "").lower()
    except ValueError:
        return ""


@lru_cache(maxsize=60000)
def canonical_url(url):
    """Stable URL used for identity and dedupe (query/fragment removed)."""
    raw = str(url or "").strip()
    if not raw:
        return ""
    try:
        parsed = urllib.parse.urlsplit(raw)
    except ValueError:
        return raw
    scheme = (parsed.scheme or "https").lower()
    host = (parsed.hostname or "").lower()
    if not host:
        return raw
    port = ""
    try:
        if parsed.port and parsed.port not in (80, 443):
            port = ":%d" % parsed.port
    except ValueError:
        port = ""
    path = re.sub(r"/+", "/", parsed.path or "/")
    if len(path) > 1:
        path = path.rstrip("/")
    return "%s://%s%s%s" % (scheme, host, port, path)


@lru_cache(maxsize=60000)
def referral_params(url):
    """Return the tracked/affiliate query parameters without altering the URL."""
    try:
        query = urllib.parse.parse_qs(urllib.parse.urlsplit(str(url or "")).query)
    except ValueError:
        return []
    found = []
    for key in query:
        lower = key.lower()
        if lower in REFERRAL_PARAMS or lower.startswith("utm_"):
            found.append(key)
    return sorted(found)


@lru_cache(maxsize=60000)
def _apify_actor(url):
    """Return ``(publisher, actor_slug)`` for an Apify Store actor URL."""
    try:
        parsed = urllib.parse.urlsplit(str(url or ""))
    except ValueError:
        return None
    if (parsed.hostname or "").lower() not in ("apify.com", "www.apify.com"):
        return None
    parts = [part for part in (parsed.path or "").split("/") if part]
    if len(parts) < 2:
        return None
    publisher = parts[0]
    slug = parts[1]
    if not re.fullmatch(r"[A-Za-z0-9_.~-]+", publisher):
        return None
    if not re.fullmatch(r"[A-Za-z0-9_.~-]+", slug):
        return None
    return publisher, slug


def stable_id(row):
    """Stable identifier derived from the source identifier, not row order."""
    actor = _apify_actor(row.get("source_url"))
    if actor:
        return "apify:%s/%s" % (actor[0].lower(), actor[1].lower())
    collection = row.get("collection") or ""
    if collection:
        return "featured:%s:%s" % (_slug(collection), _slug(row.get("name")))
    return "url:%s" % hashlib.sha1(
        canonical_url(row.get("source_url")).encode("utf-8")
    ).hexdigest()[:20]


def fingerprint(entry):
    payload = "\n".join([
        str(entry.get("name") or ""),
        str(entry.get("description") or ""),
        str(entry.get("source_url") or ""),
        ",".join(sorted(entry.get("category_ids") or [])),
    ])
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()[:16]


