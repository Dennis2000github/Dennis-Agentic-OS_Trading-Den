"""Normalized catalog for the API Mega List repository.

The upstream repository is generated by ``settings/generate_readme_clean.js``.
It publishes one README per category, plus a featured/sponsored collection.
Every row in a category README is an Apify Store actor listing with an
affiliate parameter; the featured collection rows point at APIMesa.

This module parses *only* what the source actually states. It never invents a
pricing model, authentication scheme, documentation URL, API base URL, or
"tested" status. Unknown metadata stays ``unknown``/``None`` and the evidence
that produced a derived value is kept next to it.

The normalized index is written to ``CATALOG.json`` next to the snapshot. It is
shared catalog data; per-owner saved entries, notes and readiness plans live in
``backend.megalist_store``.
"""

