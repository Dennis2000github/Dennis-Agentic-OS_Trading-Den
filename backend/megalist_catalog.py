def _atomic_write_json(path, payload):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path) or ".",
                               prefix=".catalog-", suffix=".json")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, indent=1, ensure_ascii=False)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except Exception:
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise


def _validate_index(index, previous=None):
    if not isinstance(index, dict) or not isinstance(index.get("entries"), list):
        raise CatalogError("The parsed catalog is not a valid index.", "index_invalid", 500)
    entries = index["entries"]
    if not entries:
        if previous and len(previous.get("entries") or []) >= 50:
            raise CatalogError(
                "The refreshed snapshot produced no entries; the previous catalog was kept.",
                "index_incomplete", 502,
            )
        return
    if previous and len(previous.get("entries") or []) >= 100:
        old = len(previous["entries"])
        if len(entries) < max(10, int(old * 0.5)):
            raise CatalogError(
                "The refreshed snapshot produced %d entries (previous %d); "
                "the previous catalog was kept." % (len(entries), old),
                "index_incomplete", 502,
            )
    parse_errors = int(index.get("error_count") or 0)
    if len(entries) > 50 and parse_errors > len(entries):
        raise CatalogError(
            "The refreshed snapshot has more parse errors than entries; "
            "the previous catalog was kept.",
            "index_incomplete", 502,
        )


def write_index(index):
    path = index_path()
    _atomic_write_json(path, index)
    with _lock:
        _cache["mtime"] = None
        _cache["data"] = None
    return path


def read_index():
    path = index_path()
    if not os.path.isfile(path):
        return None
    try:
        if os.path.getsize(path) > MAX_INDEX_BYTES:
            raise CatalogError("The catalog index is unexpectedly large.", "index_invalid", 500)
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError) as exc:
        raise CatalogError("Cannot read the catalog index: %s" % exc, "index_unreadable", 500)
    if not isinstance(data, dict) or not isinstance(data.get("entries"), list):
        raise CatalogError("The catalog index has an unsupported format.", "index_invalid", 500)
    return data


def _snapshot_commit():
    try:
        with open(megalist.SNAPSHOT_FILE, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        return str(data.get("commit") or "")
    except (OSError, ValueError):
        return ""


def ensure_index(force=False):
    """Load the index, rebuilding it when missing, stale, or explicitly forced."""
    with _lock:
        path = index_path()
        mtime = os.path.getmtime(path) if os.path.isfile(path) else None
        if (not force and _cache["data"] is not None
                and _cache["mtime"] == mtime):
            return _cache["data"]
        if not force and mtime is not None:
            try:
                data = read_index()
            except CatalogError:
                data = None
            if data is not None:
                commit = _snapshot_commit()
                if (data.get("parser_version") == PARSER_VERSION
                        and (not commit or data.get("source", {}).get("commit") == commit)):
                    _cache.update({"mtime": mtime, "data": data})
                    return data
        if not os.path.isdir(megalist.REPO_DIR):
            raise CatalogError(
                "The API Mega List repository snapshot is missing. Sync it from GitHub.",
                "repo_missing", 503,
            )
        previous = None
        if os.path.isfile(path):
            try:
                previous = read_index()
            except CatalogError:
                previous = None
        index = parse_repository(
            megalist.REPO_DIR,
            commit=_snapshot_commit(),
            synced_at="",
        )
        _validate_index(index, previous)
        write_index(index)
        return index


def rebuild_index(trigger="manual"):
    """Rebuild from the current snapshot and record an import entry."""
    started = _now()
    previous = None
    try:
        previous = read_index()
    except CatalogError:
        previous = None
    index = parse_repository(megalist.REPO_DIR, commit=_snapshot_commit(), synced_at="")
    _validate_index(index, previous)
    index["import"] = _diff_counts(previous, index)
    index["import"]["trigger"] = trigger
    index["import"]["started_at"] = started
    index["import"]["finished_at"] = _now()
    write_index(index)
    record_history("success", index, trigger, error="")
    return index


def _entry_map(index):
    return {entry.get("id"): entry for entry in (index or {}).get("entries") or []}


def _diff_counts(previous, current):
    old = _entry_map(previous)
    new = _entry_map(current)
    created = len([key for key in new if key not in old])
    updated = len([
        key for key in new
        if key in old and old[key].get("fingerprint") != new[key].get("fingerprint")
    ])
    unchanged = len([key for key in new if key in old]) - updated
    removed = len([key for key in old if key not in new])
    return {
        "created": created,
        "updated": updated,
        "unchanged": unchanged,
        "removed": removed,
        "failed": int(current.get("error_count") or 0),
        "skipped": int((current.get("counts") or {}).get("skipped") or 0),
        "duplicates_merged": int((current.get("counts") or {}).get("duplicates_merged") or 0),
        "entries": len(new),
    }


