def _searchable(entry):
    parts = [
        entry.get("name"), entry.get("description"), entry.get("provider_name"),
        entry.get("provider_platform"), entry.get("category"),
        entry.get("integration_type"), entry.get("pricing_model"),
        entry.get("authentication_type"), " ".join(entry.get("tags") or []),
        _host(entry.get("source_url")), " ".join(entry.get("category_ids") or []),
    ]
    return " ".join(str(part or "") for part in parts).casefold()


def _saved_view(entry, saved_map):
    record = (saved_map or {}).get(entry.get("id"))
    if not record:
        return False, False, None
    changed = bool(record.get("fingerprint")
                   and record.get("fingerprint") != entry.get("fingerprint"))
    return True, changed, record


def _verification_view(entry, verify_map):
    record = (verify_map or {}).get(entry.get("id")) or {}
    if not record:
        return {
            "status": "indexed",
            "label": "Indexed",
            "checked_at": None,
            "stale": False,
            "http_status": None,
            "error": "",
        }
    stale = bool(record.get("commit") and entry.get("source_commit")
                 and record.get("commit") != entry.get("source_commit"))
    status = record.get("status") or "indexed"
    if stale and status == "source_link_checked":
        status = "indexed"
    return {
        "status": status,
        "label": _verification_label(status),
        "checked_at": record.get("checked_at"),
        "stale": stale,
        "http_status": record.get("http_status"),
        "error": record.get("error") or "",
        "reported_broken": bool(record.get("reported_broken")),
        "final_url": record.get("final_url") or "",
        "method": record.get("method") or "",
    }


def _verification_label(status):
    return {
        "indexed": "Indexed",
        "source_link_checked": "Source link checked",
        "documentation_available": "Documentation available",
        "integration_tested": "Integration tested",
        "needs_review": "Needs review",
        "unavailable": "Unavailable",
    }.get(status, "Indexed")


