def _facets(entries, saved_map, verify_map):
    categories = {}
    providers = {}
    pricing = {}
    auth = {}
    integration = {}
    verify = {}
    for entry in entries:
        for cid, cname in [(entry.get("category_id"), entry.get("category"))]:
            if cid:
                categories[cid] = categories.get(cid, 0) + 1
        provider = entry.get("provider_name") or "Unknown"
        providers[provider] = providers.get(provider, 0) + 1
        pricing[entry.get("pricing_model") or "unknown"] = pricing.get(
            entry.get("pricing_model") or "unknown", 0) + 1
        auth[entry.get("authentication_type") or "unknown"] = auth.get(
            entry.get("authentication_type") or "unknown", 0) + 1
        integration[entry.get("integration_type") or "unknown"] = integration.get(
            entry.get("integration_type") or "unknown", 0) + 1
        status = _verification_view(entry, verify_map)["status"]
        verify[status] = verify.get(status, 0) + 1
    top_providers = sorted(providers.items(), key=lambda item: (-item[1], item[0].casefold()))[:200]
    return {
        "categories": [
            {"id": key, "count": value}
            for key, value in sorted(categories.items())
        ],
        "providers": [{"name": key, "count": value} for key, value in top_providers],
        "provider_count": len(providers),
        "pricing": pricing,
        "authentication": auth,
        "integration_type": integration,
        "verification": verify,
        "saved": sum(1 for entry in entries if entry.get("id") in (saved_map or {})),
    }


def query(index, params=None, saved_map=None, verify_map=None):
    params = params or {}
    entries = list((index or {}).get("entries") or [])

    def value(name):
        raw = params.get(name)
        if isinstance(raw, list):
            raw = raw[0] if raw else ""
        return str(raw or "").strip()

    q = value("q").casefold()
    category = value("category")
    provider = value("provider").casefold()
    pricing = value("pricing").casefold()
    auth = value("auth").casefold()
    integration = value("integration").casefold()
    verification = value("verification").casefold()
    saved_filter = value("saved").casefold()
    collection = value("collection").casefold()
    source = value("source").casefold()

    if q:
        terms = [term for term in re.split(r"\s+", q) if term]
    else:
        terms = []
    selected = []
    for entry in entries:
        if category and category not in (entry.get("category_ids") or []):
            continue
        if source in ("core", "featured") and entry.get("listing_source") != (
                "featured_collection" if source == "featured" else "core_directory"):
            continue
        if provider and provider != str(entry.get("provider_name") or "").casefold():
            continue
        if pricing and pricing != str(entry.get("pricing_model") or "unknown").casefold():
            continue
        if auth and auth != str(entry.get("authentication_type") or "unknown").casefold():
            continue
        if integration and integration != str(entry.get("integration_type") or "unknown").casefold():
            continue
        if verification:
            status = _verification_view(entry, verify_map)["status"]
            if verification == "unverified" and status != "indexed":
                continue
            if verification == "verified" and status not in (
                    "source_link_checked", "documentation_available", "integration_tested"):
                continue
            if verification not in ("verified", "unverified") and verification != status:
                continue
        if saved_filter in ("saved", "unsaved"):
            is_saved = entry.get("id") in (saved_map or {})
            if saved_filter == "saved" and not is_saved:
                continue
            if saved_filter == "unsaved" and is_saved:
                continue
        if collection:
            record = (saved_map or {}).get(entry.get("id")) or {}
            if str(record.get("collection") or "").casefold() != collection:
                continue
        if terms:
            haystack = _searchable(entry)
            if not all(term in haystack for term in terms):
                continue
        selected.append(entry)

    sort = value("sort") or "name"
    if sort == "category":
        selected.sort(key=lambda item: (
            str(item.get("category") or "").casefold(),
            str(item.get("name") or "").casefold()))
    elif sort == "provider":
        selected.sort(key=lambda item: (
            str(item.get("provider_name") or "").casefold(),
            str(item.get("name") or "").casefold()))
    elif sort == "relevance" and terms:
        def score(entry):
            name = str(entry.get("name") or "").casefold()
            return (
                -sum(1 for term in terms if term in name),
                len(str(entry.get("name") or "")),
                name,
            )
        selected.sort(key=score)
    else:
        selected.sort(key=lambda item: str(item.get("name") or "").casefold())

    try:
        page_size = int(value("page_size") or 24)
    except ValueError:
        page_size = 24
    page_size = max(1, min(100, page_size))
    try:
        page = int(value("page") or 1)
    except ValueError:
        page = 1
    page = max(1, page)
    total = len(selected)
    pages = max(1, (total + page_size - 1) // page_size)
    if page > pages:
        page = pages
    start = (page - 1) * page_size
    items = [
        summary(entry, saved_map, verify_map)
        for entry in selected[start:start + page_size]
    ]
    return {
        "items": items,
        "total": total,
        "page": page,
        "page_size": page_size,
        "pages": pages,
        "has_next": page < pages,
        "has_prev": page > 1,
        "facets": _facets(entries, saved_map, verify_map),
        "query": {
            "q": value("q"), "category": category, "provider": value("provider"),
            "pricing": pricing, "auth": auth, "integration": integration,
            "verification": verification, "saved": saved_filter,
            "collection": value("collection"), "source": source, "sort": sort,
        },
    }


