from . import megalist

PARSER_VERSION = "2026-10-23.1"
INDEX_FILENAME = "CATALOG.json"
REPOSITORY_URL = "https://github.com/cporter202/API-mega-list"
CATEGORY_RE = re.compile(r"^(?P<slug>.+)-apis-(?P<count>\d+)$")
TABLE_ROW_RE = re.compile(
    r"^\|\s*\[(?P<name>.*?)\]\((?P<url>https?://[^)\s]+)\)\s*\|\s*(?P<desc>.*?)\s*\|\s*$"
)
BULLET_RE = re.compile(
    r"^-\s*\*\*\[(?P<name>.*?)\]\((?P<url>https?://[^)\s]+)\)\*\*\s*-\s*(?P<desc>.*)$"
)
HEADING_RE = re.compile(r"^##\s+(?P<title>.+?)\s*$")
REFERRAL_PARAMS = {"fpr", "ref", "referrer", "aff", "affiliate", "aff_id", "partner"}
MAX_INDEX_BYTES = 96 * 1024 * 1024
MAX_DESCRIPTION = 1200

_lock = threading.RLock()
_cache = {"mtime": None, "data": None}


class CatalogError(Exception):
    def __init__(self, message, code="catalog_error", status=400):
        super().__init__(message)
        self.code = code
        self.status = status


