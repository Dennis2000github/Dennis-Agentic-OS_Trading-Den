def _pricing(name, description):
    """Conservative pricing hint. Returns ``(model, evidence, confidence)``.

    ``unknown`` is the default: the source rarely states commercial terms and a
    mention of "free" can describe a target site rather than the listing.
    """
    text = ("%s %s" % (name or "", description or "")).lower()
    if not text.strip():
        return "unknown", "", "none"
    if "freemium" in text or "free tier" in text or "free plan" in text:
        return "freemium", "source mentions a free tier/plan", "medium"
    paid_signals = (
        "pay-per", "pay per", "per 1k", "per 1,000", "per result", "per call",
        "price per", "pricing", "paid plan", "subscription", "$",
    )
    for signal in paid_signals:
        if signal in text:
            return "paid", "source mentions %r" % signal, "low"
    if re.search(r"\bfree\b", text) and "free trial" not in text:
        return "free", "source mentions free", "low"
    return "unknown", "", "none"


def _authentication(name, description, platform):
    text = ("%s %s" % (name or "", description or "")).lower()
    if "oauth" in text:
        return "oauth", "source mentions OAuth"
    if "no api key" in text or "no login" in text or "no credentials" in text:
        # This usually describes the scraped target site, not the platform.
        if platform == "Apify":
            return "api_key", "Apify platform requires an API token to run actors"
        return "none", "source says no login/API key is required"
    if "api key" in text or "api token" in text:
        return "api_key", "source mentions an API key/token"
    if platform == "Apify":
        return "api_key", "Apify platform requires an API token to run actors"
    if platform == "APIMesa":
        return "api_key", "the featured collection states one API key is used"
    return "unknown", ""


def _integration_type(name, description, platform, category_ids):
    text = ("%s %s" % (name or "", description or "")).lower()
    if "mcp" in text or "mcp" in " ".join(category_ids or []):
        return "mcp_server", "source name/description/category mentions MCP"
    if platform == "Apify":
        if any(word in text for word in ("scrap", "crawl", "extract", "actor")):
            return "scraping_service", "Apify Store actor listing"
        return "marketplace_listing", "Apify Store actor listing"
    if platform == "APIMesa":
        return "marketplace_listing", "sponsored marketplace collection listing"
    return "unknown", ""


def _provider(source_url, platform, collection):
    if platform == "Apify":
        actor = _apify_actor(source_url)
        if actor:
            return actor[0], "Apify"
    if platform == "APIMesa":
        return "APIMesa", "APIMesa"
    host = _host(source_url)
    return (host or "Unknown"), (collection or "Unknown source")


def _official_website(source_url, platform, collection):
    # Only return a URL the source itself supports. For Apify rows the actor
    # page is the listing, not the publisher's homepage, so no separate
    # official website is claimed.
    if platform == "APIMesa":
        return "https://apimesa.com/"
    return None


def derive_entry(row, category_lookup, commit, generated_at):
    """Turn one parsed source row into a normalized catalog record."""
    name = _strip_markdown(row.get("name"))
    description = _strip_markdown(row.get("description"))[:MAX_DESCRIPTION]
    source_url = str(row.get("source_url") or "").strip()
    platform = row.get("platform") or "Unknown"
    category_ids = sorted(set(row.get("category_ids") or []))
    categories = [
        {"id": cid, "name": category_lookup.get(cid, cid)}
        for cid in category_ids
    ]
    primary = category_ids[0] if category_ids else ""
    provider_name, provider_platform = _provider(source_url, platform, row.get("collection"))
    pricing, pricing_evidence, pricing_confidence = _pricing(name, description)
    auth, auth_evidence = _authentication(name, description, platform)
    integration_type, integration_evidence = _integration_type(
        name, description, platform, category_ids
    )
    refs = referral_params(source_url)
    sponsored = bool(row.get("sponsored"))
    tags = []
    if integration_type == "mcp_server":
        tags.append("mcp")
    if integration_type == "scraping_service":
        tags.append("scraper")
    if sponsored:
        tags.append("sponsored")
    if refs:
        tags.append("referral")
    entry = {
        "id": stable_id(row),
        "name": name or "Untitled listing",
        "description": description,
        "description_source": row.get("description_source") or row.get("source_path") or "",
        "category": category_lookup.get(primary, primary),
        "category_id": primary,
        "categories": categories,
        "category_ids": category_ids,
        "provider_name": provider_name,
        "provider_platform": provider_platform,
        "source_repository": REPOSITORY_URL,
        "source_path": row.get("source_path") or "",
        "source_url": source_url,
        "source_url_clean": canonical_url(source_url),
        "documentation_url": None,
        "official_website_url": _official_website(source_url, platform, row.get("collection")),
        "integration_type": integration_type,
        "integration_evidence": integration_evidence,
        "pricing_model": pricing,
        "pricing_evidence": pricing_evidence,
        "pricing_confidence": pricing_confidence,
        "authentication_type": auth,
        "authentication_evidence": auth_evidence,
        "tags": tags,
        "verification_status": "indexed",
        "last_verified_at": None,
        "sponsored": sponsored,
        "referral": bool(refs),
        "referral_params": refs,
        "listing_source": row.get("listing_source") or "core_directory",
        "collection": row.get("collection") or "",
        "source_commit": commit or "",
        "created_at": generated_at,
        "updated_at": generated_at,
        "date_provenance": "ingestion",
    }
    entry["fingerprint"] = fingerprint(entry)
    return entry


